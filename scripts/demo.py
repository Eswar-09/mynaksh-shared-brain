"""Replay the brief's example conversation against a running server and write samples/.

Usage:  python scripts/demo.py [base_url]     (default http://localhost:8000)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import httpx

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8000"
USER = "user-123"
STEPS = [
    ("First conversation", "session-456",
     "My name is Rahul. I was born on 15 August 1995 in Delhi. I'm planning to switch jobs next year."),
    ("Later in the same conversation", "session-456", "What should I focus on for my career?"),
    ("Follow-up", "session-456", "Why do you say that?"),
    ("New information worth remembering", "session-456",
     "I'm preparing for a product management interview next month."),
    ("Small talk is not stored", "session-456", "Thanks, that helps!"),
    ("New conversation: recall", "session-789", "What do you remember about my career goals?"),
    ("Irrelevant memory stays out", "session-789", "I love photography. Any tips for my love life this year?"),
    ("Correction", "session-789", "Actually I was born in Mumbai, not Delhi."),
]


def main() -> None:
    out = ["# Sample requests and responses", "",
           f"Generated by `scripts/demo.py` against `{BASE}`.", ""]
    with httpx.Client(base_url=BASE, timeout=60) as c:
        for title, session, msg in STEPS:
            req = {"user_id": USER, "session_id": session, "message": msg}
            r = c.post("/chat", json=req)
            out += [f"## {title}", "", "```http", "POST /chat", json.dumps(req, indent=2), "```", "",
                    f"Response `{r.status_code}`:", "", "```json", json.dumps(r.json(), indent=2,
                    ensure_ascii=False), "```", ""]
            print(f"{title}: {r.status_code} context_used={r.json().get('context_used')}")
        mems = c.get(f"/users/{USER}/memories", params={"include_history": True}).json()
        prof = c.get(f"/users/{USER}").json()
        out += ["## Final profile", "", "```http", f"GET /users/{USER}", "```", "", "```json",
                json.dumps(prof, indent=2), "```", "",
                "## Shared Brain contents, including superseded history", "", "```http",
                f"GET /users/{USER}/memories?include_history=true", "```", "", "```json",
                json.dumps(mems, indent=2), "```", ""]
    Path(__file__).resolve().parents[1].joinpath("samples", "sample_requests.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
